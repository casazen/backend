using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Casazen.Core.Entities.Enums;
using Casazen.Core.Multitenancy;

namespace Casazen.Core.Entities;

/// <summary>
/// Marketing campaign for guest communication (NF-24, ADR-014).
/// Linked to a segment for recipient selection, with approval workflow and scheduling.
/// </summary>
[Table("Campaigns")]
public class Campaign : ITenantOwned
{
    [Key]
    public Guid Id { get; set; } = Guid.NewGuid();

    /// <summary>Tenant: the org that owns this campaign (TN-1).</summary>
    public Guid OrgId { get; set; }

    /// <summary>Segment that defines campaign recipients (ADR-014-R3).</summary>
    public Guid SegmentId { get; set; }
    public virtual GuestSegment? Segment { get; set; }

    /// <summary>Email subject line.</summary>
    [Required]
    [MaxLength(200)]
    public string Subject { get; set; } = string.Empty;

    /// <summary>Email body (HTML).</summary>
    [Required]
    public string Body { get; set; } = string.Empty;

    /// <summary>True if the campaign content was generated by AI (AC-NF24-4).</summary>
    public bool IsAiGenerated { get; set; } = false;

    /// <summary>Campaign lifecycle status (AC-NF24-5, AC-NF24-6).</summary>
    public CampaignStatus Status { get; set; } = CampaignStatus.Draft;

    /// <summary>When the campaign is scheduled to send (AC-NF24-6).</summary>
    public DateTime? ScheduledAt { get; set; }

    /// <summary>When the campaign was actually sent (AC-NF24-10).</summary>
    public DateTime? SentAt { get; set; }

    /// <summary>Number of emails successfully sent (AC-NF24-10).</summary>
    public int SentCount { get; set; } = 0;

    /// <summary>Number of emails that failed to send (AC-NF24-10).</summary>
    public int ErrorCount { get; set; } = 0;

    /// <summary>Number of recipients who unsubscribed after this campaign (AC-NF24-7, AC-NF24-10).</summary>
    public int UnsubscribeCount { get; set; } = 0;

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}
