using System.Globalization;
using Casazen.Core.Entities;
using Casazen.Core.Utilities;

namespace Casazen.Core.Services;

/// <summary>The types of item of the approval queue (<see cref="ApprovalQueueItem.ItemType"/>). The ones that have an action are registered by <c>AddApprovalQueueActions</c>.</summary>
public static class ApprovalItemTypes
{
    /// <summary>A marketing campaign waiting for approval before it can be scheduled (NF-24): approving it approves the campaign and schedules it.</summary>
    public const string Campaign = "Campaign";

    /// <summary>The draft of a message to a guest, written by the assistant (E05/F05): approving it sends the text to the conversation.</summary>
    public const string MessageDraft = "MessageDraft";

    /// <summary>A message of a routine in test mode (NF-06): a pure decision.</summary>
    public const string Routine = "Routine";

    /// <summary>A text generated by the AI (NF-06): a pure decision.</summary>
    public const string AiText = "AiText";
}

/// <summary>The names of what approving an item does (<see cref="ApprovalQueueItem.OriginAction"/>), stored by name.</summary>
public static class ApprovalOriginActions
{
    /// <summary>The text goes to the conversation of the guest (<c>MessageDraftApprovalAction</c>).</summary>
    public const string SendGuestMessage = "SendGuestMessage";

    /// <summary>The campaign is approved and, when it has a time, scheduled (<c>CampaignApprovalAction</c>).</summary>
    public const string ApproveCampaign = "ApproveCampaign";

    /// <summary>The reply to a review is sent (the reviews are not part of the product yet: no action is registered for it).</summary>
    public const string SendReviewReply = "SendReviewReply";

    /// <summary>Nothing runs: the approval is the whole decision.</summary>
    public const string None = "None";
}

/// <summary>
/// The rules of the approval queue (E05/F04/US01, NF-68), in one place and with no clock or database, so the API, the actions and the tests cannot
/// disagree: the stable codes of the answers, the text of an edit, the reason of a rejection and the key of the send of an approved message.
/// </summary>
public static class ApprovalQueueRules
{
    /// <summary>Days an item waits for a decision before the daily job expires it.</summary>
    public const int ExpirationDays = 7;

    /// <summary>
    /// Days the words of an item (its text, the host's edit of it and the reason of a rejection) are kept after the item was decided or expired: then the daily job empties them
    /// (<c>ApprovalExpirationJob</c>); the decision, its author, its time and the action stay. A documented constant and not a setting: the queue is working data, short-lived by
    /// design (an item waits seven days), and the message it carries is a copy of the one of the conversations, whose own retention is <c>Gdpr:Retention:AlloggiatiData</c> (docs/runbooks/gdpr.md § 14).
    /// The erasure of a guest empties the items of its conversations at once, with no wait.
    /// </summary>
    public const int TextRetentionDays = 30;

    /// <summary>The push category the app registers (with its Approve and Edit buttons) for the alert of an item waiting for approval (the <c>categoryId</c> of the push).</summary>
    public const string PushCategory = "draft-ready";

    /// <summary>The text of an edit is not usable: it is empty, a message is longer than <see cref="GuestMessageRules.TextMaxLength"/>, or a campaign has no subject line, blank line and body (422).</summary>
    public const string EditInvalidCode = "approval_edit_invalid";

    /// <summary>A rejection without its reason, or with one longer than <see cref="ApprovalQueueItem.RejectionReasonMaxLength"/> characters (422).</summary>
    public const string RejectionReasonRequiredCode = "approval_rejection_reason_required";

    /// <summary>The action the item was waiting for failed: the item stays pending with the code in <see cref="ApprovalQueueItem.OriginActionError"/>, and the host can edit and try again (409).</summary>
    public const string OriginActionFailedCode = "approval_origin_action_failed";

    /// <summary>The item was already decided or has expired (409).</summary>
    public const string NotPendingCode = "approval_item_not_pending";

    /// <summary>The item is not there, is of another org or is out of the reach of the caller (404).</summary>
    public const string NotFoundCode = "approval_item_not_found";

    /// <summary>The code of a failed action that raised something unexpected: the item stays pending and the error is the server's, in its log.</summary>
    public const string UnexpectedErrorCode = "origin_action_error";

    /// <summary>The longest subject line of a campaign: the column <c>Campaign.Subject</c> (a test pins the two together).</summary>
    public const int CampaignSubjectMaxLength = 200;

    /// <summary>How many times the message of an item can be refused by the channel and sent again, each time with the next key (<see cref="SendKeyOf"/>).</summary>
    public const int MaxSendAttempts = 10;

    /// <summary>The code of a message that the channel refused <see cref="MaxSendAttempts"/> times: the host rejects the item or writes the answer by hand.</summary>
    public const string SendAttemptsExhaustedCode = "approval_send_attempts_exhausted";

    /// <summary>
    /// The key a message sends with (<c>IMessageReplyService.ReplyAsync</c>): one per item, so a second approval of the same item (a double click, two
    /// hosts, a retry after a timeout) reaches the guest once. It follows the rule of <see cref="GuestMessageRules.NormalizeIdempotencyKey"/>: only
    /// letters, digits, dashes and underscores (a colon would be refused as <c>idempotency_key_invalid</c>), 8 to 64 characters.
    /// </summary>
    /// <param name="itemId">The item of the queue.</param>
    /// <param name="attempt">
    /// 1 for the first send (<c>approval-{id}</c>). A message the channel manager <b>refused</b> did not go out, but the same key would replay that refusal
    /// for ever: the action sends again with the key of the next attempt (<c>approval-{id}-2</c>, ...), which only happens after a refusal, never after a send
    /// whose outcome is not known (that one is the same message, checked on the channel).
    /// </param>
    public static string SendKeyOf(Guid itemId, int attempt = 1)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(attempt, 1);
        return attempt == 1 ? $"approval-{itemId:D}" : $"approval-{itemId:D}-{attempt}";
    }

    /// <summary>
    /// The instant an alert was raised as it is written in the keys of the push, of the bell and of the e-mail slot: UTC, whole seconds, <c>yyyyMMddHHmmss</c>, with the invariant
    /// culture (a custom format of a <see cref="DateTime"/> takes its calendar from the culture, so a machine with another culture would write another key). Two alerts of one item a second
    /// apart are two alerts; an alert raised again for the same moment has the same stamp.
    /// </summary>
    public static string StampOf(DateTime raisedAtUtc) =>
        UtcDateTime.Normalize(raisedAtUtc).ToString("yyyyMMddHHmmss", CultureInfo.InvariantCulture);

    /// <summary>
    /// The text of an edit as it is stored, or <c>null</c> when it is not usable (<see cref="EditInvalidCode"/>). A message draft is plain text
    /// (<see cref="GuestMessageRules.NormalizeText"/>) of at most <see cref="GuestMessageRules.TextMaxLength"/> characters; a campaign is its subject line, a
    /// blank line and its body (<see cref="TryParseCampaignText"/>); any other type only has to say something.
    /// </summary>
    public static string? NormalizeEditedText(string itemType, string? text)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(itemType);

        if (string.IsNullOrWhiteSpace(text))
            return null;

        if (string.Equals(itemType, ApprovalItemTypes.MessageDraft, StringComparison.Ordinal))
        {
            return GuestMessageRules.NormalizeText(text) is { Length: <= GuestMessageRules.TextMaxLength } message ? message : null;
        }

        if (string.Equals(itemType, ApprovalItemTypes.Campaign, StringComparison.Ordinal))
        {
            return TryParseCampaignText(text, out var subject, out var body) ? CampaignTextOf(subject, body) : null;
        }

        return text.Trim();
    }

    /// <summary>
    /// The subject and the body of the text of a campaign item: the text is the subject on one line, a blank line, and the body (the text of the item
    /// that <c>CampaignService</c> writes). False for a text with no blank line, an empty subject or body, a subject of several lines or longer than the
    /// column.
    /// </summary>
    public static bool TryParseCampaignText(string? text, out string subject, out string body)
    {
        subject = string.Empty;
        body = string.Empty;
        if (string.IsNullOrWhiteSpace(text))
            return false;

        var normalized = text.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').Trim();
        var split = normalized.IndexOf("\n\n", StringComparison.Ordinal);
        if (split <= 0)
            return false;

        var candidateSubject = normalized[..split].Trim();
        var candidateBody = normalized[(split + 2)..].Trim();
        if (candidateSubject.Length is 0 or > CampaignSubjectMaxLength
            || candidateSubject.Contains('\n', StringComparison.Ordinal)
            || candidateBody.Length == 0)
        {
            return false;
        }

        subject = candidateSubject;
        body = candidateBody;
        return true;
    }

    /// <summary>The text of a campaign item: the subject, a blank line and the body (the form <see cref="TryParseCampaignText"/> reads).</summary>
    public static string CampaignTextOf(string subject, string body) => $"{subject}\n\n{body}";

    /// <summary>
    /// The reason of a rejection as it is stored: trimmed, line breaks as <c>\n</c>; <c>null</c> when there is none or when it is longer than
    /// <see cref="ApprovalQueueItem.RejectionReasonMaxLength"/> characters (<see cref="RejectionReasonRequiredCode"/>).
    /// </summary>
    public static string? NormalizeRejectionReason(string? reason)
    {
        if (string.IsNullOrWhiteSpace(reason))
            return null;

        var normalized = reason.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').Trim();
        return normalized.Length <= ApprovalQueueItem.RejectionReasonMaxLength ? normalized : null;
    }
}
